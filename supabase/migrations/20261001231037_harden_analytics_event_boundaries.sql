
-- Harden analytics event boundaries and SECURITY DEFINER trigger helpers.
-- Public clients may record views/shares, but may not manufacture acquisition/conversion events.

CREATE OR REPLACE FUNCTION public.validate_public_initiative_event_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  jwt_role text := coalesce((select auth.jwt() ->> 'role'), '');
BEGIN
  IF new.event_type IS NULL
     OR new.event_type NOT IN ('initiative_view','share_click','member_acquired','member_conversion') THEN
    RAISE EXCEPTION 'Invalid public initiative event type';
  END IF;

  IF new.event_type IN ('member_acquired','member_conversion')
     AND jwt_role <> 'service_role' THEN
    RAISE EXCEPTION 'Acquisition and conversion events must be generated by the backend';
  END IF;

  IF new.user_id IS NOT NULL AND new.user_id <> (select auth.uid()) THEN
    new.user_id := NULL;
  END IF;

  RETURN new;
END;
$function$;

DROP POLICY IF EXISTS "Public can insert validated initiative events" ON public.initiative_events;
CREATE POLICY "Public can insert validated initiative events"
ON public.initiative_events
AS PERMISSIVE
FOR INSERT
TO anon, authenticated
WITH CHECK (
  event_type IN ('initiative_view','share_click')
  AND (user_id IS NULL OR user_id = (select auth.uid()))
  AND (session_id IS NULL OR (length(session_id) >= 1 AND length(session_id) <= 128))
  AND (
    initiative_id IS NULL
    OR EXISTS (
      SELECT 1
      FROM public.initiatives i
      WHERE i.id = initiative_events.initiative_id
        AND i.is_approved = true
        AND i.is_published = true
    )
  )
  AND (
    campaign_link_id IS NULL
    OR EXISTS (
      SELECT 1
      FROM public.campaign_links c
      WHERE c.id = initiative_events.campaign_link_id
        AND c.is_active = true
    )
  )
  AND jsonb_typeof(coalesce(metadata, '{}'::jsonb)) = 'object'
);

CREATE OR REPLACE FUNCTION public.update_initiative_counters()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF (NEW.event_type = 'page_view') THEN
    UPDATE public.initiatives
    SET view_count = view_count + 1
    WHERE id = NEW.initiative_id;
  ELSIF (NEW.event_type = 'member_acquired') THEN
    UPDATE public.initiatives
    SET conversion_count = conversion_count + 1,
        active_supporter_count = active_supporter_count + 1
    WHERE id = NEW.initiative_id;
  ELSIF (NEW.event_type = 'supporter_activated') THEN
    UPDATE public.initiatives
    SET active_supporter_count = active_supporter_count + 1,
        inactive_supporter_count = greatest(0, inactive_supporter_count - 1)
    WHERE id = NEW.initiative_id;
  ELSIF (NEW.event_type = 'supporter_deactivated') THEN
    UPDATE public.initiatives
    SET active_supporter_count = greatest(0, active_supporter_count - 1),
        inactive_supporter_count = inactive_supporter_count + 1
    WHERE id = NEW.initiative_id;
  END IF;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_last_engagement()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NEW.user_id IS NOT NULL THEN
    UPDATE public.profiles
    SET last_engagement_at = now()
    WHERE id = NEW.user_id;
  END IF;
  RETURN NEW;
END;
$function$;

REVOKE EXECUTE ON FUNCTION public.update_initiative_counters() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.update_last_engagement() FROM PUBLIC, anon, authenticated;
