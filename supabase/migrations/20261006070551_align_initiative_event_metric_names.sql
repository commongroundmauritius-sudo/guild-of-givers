CREATE OR REPLACE FUNCTION public.validate_public_initiative_event_insert()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  jwt_role text := coalesce((select auth.jwt() ->> 'role'), '');
BEGIN
  IF new.event_type = 'page_view' THEN
    new.event_type := 'initiative_view';
  END IF;

  IF new.event_type IS NULL
     OR new.event_type NOT IN ('initiative_view','share_click','member_acquired','member_conversion') THEN
    RAISE EXCEPTION 'Invalid public initiative event type';
  END IF;

  IF new.event_type IN ('member_acquired','member_conversion')
     AND jwt_role <> 'service_role' THEN
    RAISE EXCEPTION 'Acquisition and conversion events must be generated by the backend';
  END IF;

  IF new.user_id IS NOT NULL AND new.user_id <> (select auth.uid()) THEN
    new.user_id := NULL;
  END IF;

  RETURN new;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_initiative_counters()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NEW.event_type = 'initiative_view' THEN
    UPDATE public.initiatives
    SET view_count = COALESCE(view_count, 0) + 1
    WHERE id = NEW.initiative_id;
  ELSIF NEW.event_type = 'member_acquired' THEN
    UPDATE public.initiatives
    SET conversion_count = COALESCE(conversion_count, 0) + 1,
        active_supporter_count = COALESCE(active_supporter_count, 0) + 1
    WHERE id = NEW.initiative_id;
  ELSIF NEW.event_type = 'supporter_activated' THEN
    UPDATE public.initiatives
    SET active_supporter_count = COALESCE(active_supporter_count, 0) + 1,
        inactive_supporter_count = GREATEST(0, COALESCE(inactive_supporter_count, 0) - 1)
    WHERE id = NEW.initiative_id;
  ELSIF NEW.event_type = 'supporter_deactivated' THEN
    UPDATE public.initiatives
    SET active_supporter_count = GREATEST(0, COALESCE(active_supporter_count, 0) - 1),
        inactive_supporter_count = COALESCE(inactive_supporter_count, 0) + 1
    WHERE id = NEW.initiative_id;
  END IF;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.reconcile_initiative_analytics(p_initiative_id uuid DEFAULT NULL::uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  UPDATE public.initiatives i
  SET
    view_count = (
      SELECT count(*)
      FROM public.initiative_events
      WHERE initiative_id = i.id
        AND event_type = 'initiative_view'
    ),
    conversion_count = (
      SELECT count(*)
      FROM public.initiative_events
      WHERE initiative_id = i.id
        AND event_type = 'member_acquired'
    ),
    active_supporter_count = (
      SELECT count(*)
      FROM public.profiles p
      WHERE p.primary_initiative_id = i.id
        AND EXISTS (
          SELECT 1
          FROM public.subscriptions s
          WHERE s.user_id = p.id
            AND s.status = 'active'
        )
    )
  WHERE p_initiative_id IS NULL OR i.id = p_initiative_id;
END;
$function$;

REVOKE ALL ON FUNCTION public.reconcile_initiative_analytics(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reconcile_initiative_analytics(uuid) TO service_role;
